"""backendpin — the application decides its own GDK backend (ROUND 24).

Why this exists (references/ROUND24-BRIEF.md §0, operator-measured on 0.2.7):
the position-restore code is CORRECT — an X11 client launched with the
backend pinned lands exactly on the saved rect (2700,200,900,700) — but the
user's real launch paths are UNPINNED.  `gtk-launch` on the shadowing
user-level desktop entry, and `/usr/bin/reelsee` from a terminal, both
produce a NATIVE WAYLAND client, where positioning is impossible by
protocol (xdg-shell has no position request) and Mutter centres the window.
The packaged `.desktop` entry pins the backend in its `Exec=` line, but
desktop files get shadowed, copied, edited or regenerated by users — so a
`.desktop` file is not a durable place for a behaviour the app depends on.
This module puts the decision in the application, before GDK opens a
display.

Two pieces only, both pure (no `gi`, no display, no side effects beyond the
one environment write), so the whole table is unit-testable headlessly:

  * :func:`pin_decision` — the §A decision table, first match wins;
  * :func:`apply_pin`    — apply it to ``os.environ`` and say so ONCE.

Ordering contract (enforced at the call site in ``reelsee.run()``): the pin
must happen AFTER ``Config()`` (the preference lives there) and BEFORE
``engine.apply_renderer_override()`` — that call may ``os.execv`` and the
child must inherit the pin — and before ``gi`` is imported, because the
first process that opens a Gdk display fixes the backend for good.
"""
from __future__ import annotations

import logging
import os
import re

log = logging.getLogger("reelsee.backendpin")

#: The environment variable GDK reads to pick a display backend.
ENV_BACKEND = "GDK_BACKEND"
#: Operator escape hatch: present with ANY value ⇒ the app never pins.
ENV_PIN = "REELSEE_BACKEND_PIN"
#: In-process marker naming the value this process pinned (grep-able, and
#: inherited by the re-exec child so the pin survives a renderer override).
ENV_PINNED = "REELSEE_BACKEND_PINNED"
#: Config key (``ui.x11_backend``): ``auto`` | ``x11`` | ``wayland``.
CONFIG_KEY = "ui.x11_backend"

#: Raw-Xlib placement only works on X11, so that is the only value we set.
PIN_VALUE = "x11"
X11_SOCKET_DIR = "/tmp/.X11-unix"

PREF_AUTO = "auto"
PREF_X11 = "x11"
PREF_WAYLAND = "wayland"

# ``:N`` and ``:N.S`` are the only DISPLAY forms whose socket we can name.
# ``host:N``, ``abstract:…`` and anything else are NOT confirmable, and we
# never pin a backend we cannot prove exists (fail-closed).
_DISPLAY_RE = re.compile(r"^:(\d+)(?:\.\d+)?$")


def _nonempty(env, key: str) -> str | None:
    """The value of ``env[key]`` when it is a real choice, else None.

    Absent AND empty (or whitespace-only) both mean "not chosen": an env var
    exported as "" is not a user picking a backend, and treating it as one
    silently disables the pin (the trap §B.1 calls out)."""
    raw = env.get(key)
    if raw is None:
        return None
    s = str(raw)
    return s if s.strip() else None


def _socket_exists(display) -> bool:      # SYNC-FS-OK boot-time probe, once
    """True only when the X socket for ``display`` is really on disk.

    ``:N`` and ``:N.S`` map to ``/tmp/.X11-unix/X<N>``.  Anything else —
    ``host:N``, an abstract socket, garbage — is reported as MISSING: we do
    not pin a backend we cannot confirm exists.  This is the seam the tests
    patch; it never creates or removes anything."""
    if display is None:
        return False
    m = _DISPLAY_RE.match(str(display))
    if not m:
        return False
    return os.path.exists(os.path.join(X11_SOCKET_DIR, "X%s" % m.group(1)))


def _norm_pref(pref) -> str:
    """Config value normalised; anything unknown is ``auto`` (never an
    exception — a bad value in a settings file must not stop the boot)."""
    if pref is None:
        return PREF_AUTO
    s = str(pref).strip().lower()
    return s or PREF_AUTO


def pin_decision(env: dict | None = None,
                 pref: str | None = None) -> tuple[str | None, str]:
    """``(value_to_set_or_None, reason)`` — §A table, FIRST match wins.

    ``env`` defaults to ``os.environ``; ``pref`` is ``ui.x11_backend``.
    Pure: reads only, never mutates, never raises for a sane mapping."""
    if env is None:
        env = os.environ
    # 1/2: an explicit choice by the user or the operator always wins.
    if _nonempty(env, ENV_BACKEND):
        return (None, "explicit-env")
    if _nonempty(env, ENV_PIN):
        return (None, "explicit-pin-env")
    # 3/4: the config preference.
    want = _norm_pref(pref)
    if want == PREF_WAYLAND:
        return (None, "pref-wayland")
    if want == PREF_X11:
        return (PIN_VALUE, "pref-x11")
    # 5/6: auto — pin only inside an XWayland session we can PROVE.
    if _nonempty(env, "WAYLAND_DISPLAY") and _nonempty(env, "DISPLAY"):
        if _socket_exists(_nonempty(env, "DISPLAY")):
            return (PIN_VALUE, "xwayland")
        return (None, "no-xwayland-socket")
    # 7: nothing to decide (no Wayland, or no X to fall back to).
    return (None, "not-applicable")


def apply_pin(env: dict | None = None, pref: str | None = None,
              logger=None) -> str | None:
    """Pin ``GDK_BACKEND`` when the table says so; return the value set.

    Sets ``REELSEE_BACKEND_PINNED=<value>`` as the in-process marker (and
    hands it to the re-exec child through ``os.environ``) and logs ONE INFO
    line either way, naming the reason token verbatim so the operator can
    grep the app log for why a window did or did not get positioned.

    Contract: mutates ``os.environ`` only (never ``os.putenv``), is
    idempotent — a second call sees the ``GDK_BACKEND`` it set and is a
    no-op — and MUST NEVER RAISE: a backend decision is not worth losing a
    video window over."""
    lg = logger if logger is not None else log
    try:
        if env is None:
            env = os.environ
        value, reason = pin_decision(env, pref)
        if value is None:
            lg.info("backend pin: not pinning %s (reason=%s)",
                    ENV_BACKEND, reason)
            return None
        env[ENV_BACKEND] = value
        env[ENV_PINNED] = value
        lg.info("backend pin: %s=%s (reason=%s)",
                ENV_BACKEND, value, reason)
        return value
    except Exception as exc:                      # noqa: BLE001
        try:
            lg.warning("backend pin failed (%s: %s): leaving %s alone",
                       type(exc).__name__, exc, ENV_BACKEND)
        except Exception:                         # noqa: BLE001
            pass
        return None
