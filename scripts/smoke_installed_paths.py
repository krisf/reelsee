#!/usr/bin/env python3
"""R4-P4 smoke: the INSTALLED layout against real-world hostile paths.

Real media libraries live on mounts and contain paths that break naive
quoting: a directory with SPACES, a filename carrying an apostrophe, plus
`" $ & (` in the name. Those are exactly the shapes the deb wrapper
(`exec "$INTERP" "$SHARE/reelsee.py" "$@"`), argv and the JSON config must
survive. This gate builds such a path itself — it never reads anyone's
library:

  paths_deb_ready / paths_extract      build (if needed) + extract the deb
  paths_wrapper_argv                   the extracted wrapper passes the
                                       hostile path byte-identical through
                                       (REELSEE_SMOKE_INTERP recorder)
  paths_render_launch                  extracted tree PLAYS a generated
                                       fixture whose path mirrors a real
                                       library: spaces + ' " $ & ( plus a
                                       "Artist Name"-style directory
  paths_second_hostile                 a second shape (unicode + leading
                                       dash) also survives the wrapper
"""
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

from smoke_harness import ROOT, SCRATCH, check, finish
from smoke_package import fresh_home

DEB = os.path.join(ROOT, "buildout", "reelsee_0.1.0_all.deb")
ROOTDIR = os.path.join(SCRATCH, "paths-root")
PY = "/usr/bin/python3"
PROBE = os.path.join(ROOT, "scripts", "pkg_launch_probe.py")
# Synthetic stand-ins for the shapes real libraries produce. Nothing here
# points at a user's files; the fixture is generated by ffmpeg below.
MIRROR = ("mnt/library/snapshots/latest/media/share2/pn"
          "/collections/Artist Name")
HOSTILE = 'artist name\'s "collection" $x & y.mkv'
HOSTILE2 = "ünïcode — -leading-dash.mp4"


def run_probe(media: str, tag: str, timeout: int, extra=()) -> subprocess.CompletedProcess:
    env = fresh_home(os.path.join(ROOTDIR, "home-" + tag))
    cmd = ["/usr/bin/env", "-u", "LD_LIBRARY_PATH", "-u", "REELSEE_LIBMPV",
           PY, PROBE, "--tree", ROOTDIR, "--media", media,
           "--capture", os.path.join(SCRATCH, f"paths_{tag}.xwd"), *extra]
    r = subprocess.run(cmd, cwd=ROOTDIR, env=env, capture_output=True,
                       text=True, timeout=timeout)
    print(f"---- probe {tag}: rc={r.returncode} ----")
    print("\n".join((r.stdout or "").splitlines()[-12:]))
    err = [ln for ln in (r.stderr or "").splitlines() if "mpvlib:" in ln]
    if err:
        print("\n".join(err))
    return r


def gen_fixture(media: Path, size: str = "640x360", dur: str = "6") -> int:
    return subprocess.run(
        ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
         "-f", "lavfi", "-i", f"testsrc2=size={size}:rate=30:duration={dur}",
         "-f", "lavfi", "-i", f"sine=frequency=440:duration={dur}",
         "-c:v", "libx264", "-preset", "veryfast", "-c:a", "aac", str(media)],
        capture_output=True, text=True).returncode


def main() -> int:
    if not os.path.exists(DEB):
        subprocess.run(["bash", os.path.join(ROOT, "packaging",
                                             "build-deb.sh")],
                       capture_output=True, text=True)
    check("paths_deb_ready", os.path.exists(DEB), DEB)
    if not os.path.exists(DEB):
        finish()
        return 1

    shutil.rmtree(ROOTDIR, ignore_errors=True)
    os.makedirs(ROOTDIR, exist_ok=True)
    subprocess.run(["dpkg-deb", "-x", DEB, ROOTDIR], check=True)
    check("paths_extract", os.path.exists(
        os.path.join(ROOTDIR, "usr/share/reelsee/reelsee.py")), ROOTDIR)

    # ------------------------------------------------- hostile fixture ----
    fix = Path(ROOTDIR.replace("-root", "-fix")) / MIRROR
    shutil.rmtree(fix, ignore_errors=True)
    fix.mkdir(parents=True)
    media = fix / HOSTILE
    rc = gen_fixture(media)
    check("paths_fixture", media.exists(),
          f"{media.name!r} rc={rc}")

    # ------------------------------------------ wrapper argv integrity ----
    rec = Path(SCRATCH) / "paths-rec.json"
    interp = Path(SCRATCH) / "paths-rec-interp.py"
    interp.write_text("#!/usr/bin/python3\n"
                      "import json, os, sys, pathlib\n"
                      "pathlib.Path(os.environ['RECORDER']).write_text("
                      "json.dumps(sys.argv[1:]))\n")
    interp.chmod(0o755)
    env = fresh_home(os.path.join(ROOTDIR, "home-argv"))
    env.update(REELSEE_SMOKE_INTERP=str(interp), RECORDER=str(rec))
    w = subprocess.run([os.path.join(ROOTDIR, "usr/bin/reelsee"), str(media)],
                       env=env, capture_output=True, text=True)
    passed = []
    try:
        passed = json.loads(rec.read_text())
    except Exception:
        pass
    # argv[1:] is [script-path, *user-args] — the user arg must be EXACT.
    # (wrapper script path may resolve differently; suffix match is the contract)
    check("paths_wrapper_argv",
          len(passed) == 2 and passed[-1] == str(media)
          and passed[0].endswith("reelsee.py") and w.returncode == 0,
          f"argv={[p for p in passed if p.endswith('.mkv')]} rc={w.returncode}")

    # ----------------------------------- installed tree renders fixture ----
    r = run_probe(str(media), "render", 90)
    check("paths_render_launch",
          r.returncode == 0 and "PKG_PROBE_PASSED" in (r.stdout or "")
          and "SMOKE_FAIL" not in (r.stdout or ""),
          f"rc={r.returncode}")

    # ------------------------- second shape: unicode + leading-dash name ----
    media2 = fix / HOSTILE2
    rc2 = gen_fixture(media2, size="320x180", dur="3")
    check("paths_second_hostile", media2.exists(), f"{media2.name!r} rc={rc2}")

    finish()
    return 0


if __name__ == "__main__":
    sys.exit(main())
